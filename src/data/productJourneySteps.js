/**
 * Ürün adına göre yolculuk adımlarını döndürür
 * @param {string} productName - Ürün adı
 * @returns {Array} Yolculuk adımları dizisi
 */
export const getProductJourneySteps = (productName) => {
  if (!productName) {
    return getDefaultJourneySteps();
  }

  // Tam eşleşme kontrolü
  if (productJourneySteps[productName]) {
    return productJourneySteps[productName];
  }

  // Kısmi eşleşme kontrolü (büyük/küçük harf duyarsız)
  const normalizedName = productName.toLowerCase();
  const matchingKey = Object.keys(productJourneySteps).find(
    (key) => key.toLowerCase() === normalizedName
  );

  if (matchingKey) {
    return productJourneySteps[matchingKey];
  }

  // Anahtar kelime bazlı eşleşme
  for (const [key, steps] of Object.entries(productJourneySteps)) {
    const keyWords = key.toLowerCase().split(" ");
    const nameWords = normalizedName.split(" ");
    
    // Eğer ürün adında anahtar kelimeler varsa
    if (keyWords.some((word) => nameWords.includes(word) || normalizedName.includes(word))) {
      return steps;
    }
  }

  // Varsayılan yolculuk adımları
  return getDefaultJourneySteps();
};

